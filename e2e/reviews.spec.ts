import { test, expect } from '@playwright/test'

test('a guest posts without an account and admin can hide and restore the review', async ({ page }) => {
  const username = process.env.BLUE_E2E_USERNAME
  const password = process.env.BLUE_E2E_PASSWORD
  test.skip(!username || !password, 'Development admin credentials are required for moderation cleanup.')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const text = `Temporary guest browser review ${Date.now()}. Great website!`
  await page.goto('/')
  await page.getByRole('banner').getByRole('link', { name: 'Reviews', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Leave a review', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '4 stars', exact: true }).click()
  await page.getByLabel('Display name', { exact: false }).fill('Browser test guest')
  await page.getByLabel('Your review', { exact: true }).fill(text)
  await page.getByRole('button', { name: 'Post review', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'You made the page a little cooler.' })).toBeVisible()
  await expect(page.getByText(text, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText(text, { exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/guest-reviews-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('banner').getByRole('link', { name: 'Sign in', exact: true }).click()
  await page.getByLabel('Username', { exact: true }).fill(username!)
  await page.getByLabel('Password', { exact: true }).fill(password!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/apps$/)
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Settings', exact: true }).click()
  const review = page.locator('article').filter({ hasText: text })
  await review.getByRole('button', { name: 'Hide review', exact: true }).click()
  await expect(review).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Leave a review', exact: true })).toBeVisible()
  await expect(page.getByText(text, { exact: true })).toHaveCount(0)
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Show hidden reviews', exact: true }).click()
  await review.getByRole('button', { name: 'Restore review', exact: true }).click()
  await page.goto('/')
  await expect(page.getByText(text, { exact: true })).toBeVisible()
  await page.goto('/settings')
  await review.getByRole('button', { name: 'Hide review', exact: true }).click()
  await expect(review).toHaveCount(0)
  expect(errors).toEqual([])
})
