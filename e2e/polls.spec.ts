import { test, expect } from '@playwright/test'
test.use({ actionTimeout: 10000 })

test('homepage follows light, dark, and system modes including review controls', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Change theme' }).click()
  await page.getByRole('menuitem', { name: 'Light', exact: true }).click()
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  const light = await page.locator('.public-home').evaluate(el => getComputedStyle(el).backgroundColor)
  await page.getByRole('button', { name: 'Change theme' }).click()
  await page.getByRole('menuitem', { name: 'Dark', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  const dark = await page.locator('.public-home').evaluate(el => getComputedStyle(el).backgroundColor)
  expect(dark).not.toBe(light)
  await expect(page.getByRole('heading', { name: /Cameron.*Blue/ })).toBeVisible()
  expect(await page.getByLabel('Display name').evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe('rgb(255, 255, 255)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/home-dark.png', fullPage: true })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.getByRole('button', { name: 'Change theme' }).click()
  await page.getByRole('menuitem', { name: 'System', exact: true }).click()
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveClass(/dark/)
})

test('host publishes a quiz, two guests answer, results update live and hide securely', async ({ page, browser }) => {
  test.setTimeout(120000)
  const username = process.env.BLUE_E2E_USERNAME, password = process.env.BLUE_E2E_PASSWORD
  test.skip(!username || !password, 'Development admin credentials required.')
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/sign-in')
  await page.getByLabel('Username', { exact: true }).fill(username!)
  await page.getByLabel('Password', { exact: true }).fill(password!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/apps$/)
  await page.locator('.app-card').filter({ hasText: 'Polls & quizzes' }).click()
  await page.getByRole('link', { name: 'Create poll', exact: true }).click()
  await page.getByLabel('Poll title', { exact: true }).fill(`Blue live test ${Date.now()}`)
  await page.getByLabel('Description (optional)').fill('A live browser test on development.')
  const first = page.getByRole('region', { name: 'Question 1', exact: true })
  await first.getByLabel('Question text', { exact: true }).fill('Best color?')
  await first.getByLabel('Option 1', { exact: true }).fill('Blue')
  await first.getByLabel('Option 2', { exact: true }).fill('Red')
  await page.getByRole('combobox', { name: 'Question 1 correct answer' }).click()
  await page.getByRole('option', { name: 'Option 1 · Blue', exact: true }).click()
  await page.getByRole('button', { name: /Add question/ }).click()
  const second = page.getByRole('region', { name: 'Question 2', exact: true })
  await second.getByLabel('Question text', { exact: true }).fill('Describe your day.')
  await page.getByRole('combobox', { name: 'Question 2 type' }).click()
  await page.getByRole('option', { name: 'Open ended', exact: true }).click()
  await page.getByRole('button', { name: 'Create draft', exact: true }).click()
  const code = (await page.getByTestId('poll-code').textContent())!
  expect(code).toMatch(/^[A-Z2-9]{8}$/)
  await expect(page.locator('svg').filter({ has: page.locator('title', { hasText: 'Join Blue live test' }) })).toHaveCount(1)
  await page.getByRole('button', { name: 'Edit draft', exact: true }).click()
  await page.getByLabel('Description (optional)').fill('Updated draft description.')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await page.getByRole('button', { name: 'Publish poll', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Close voting' })).toBeVisible()
  const guestContext = await browser.newContext({ baseURL: 'http://localhost:5173', viewport: { width: 390, height: 844 } })
  const guest = await guestContext.newPage()
  const otherContext = await browser.newContext({ baseURL: 'http://localhost:5173', viewport: { width: 390, height: 844 } })
  const other = await otherContext.newPage()
  try {
    await guest.goto('/public-apps')
    await guest.getByRole('link', { name: 'Join with a code' }).click()
    await guest.getByLabel('8-character join code').fill(code)
    await guest.getByRole('button', { name: 'Find poll' }).click()
    await guest.getByRole('button', { name: 'Join poll', exact: true }).click()
    await guest.getByRole('button', { name: /A Blue/ }).click()
    await guest.getByRole('button', { name: 'Submit answer' }).click()
    await expect(guest.getByText('Answer submitted', { exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: 'Live results' })).toContainText('1 response')
    await guest.getByRole('button', { name: 'Next question' }).click()
    await guest.getByLabel('Your answer', { exact: true }).fill('Blue skies and sunny skies')
    await guest.getByRole('button', { name: 'Submit answer' }).click()
    await expect(guest.getByText('You’re all done!', { exact: true })).toBeVisible()
    await guest.getByRole('tab', { name: 'Live results' }).click()
    await expect(guest.getByText('Results are hidden', { exact: true })).toBeVisible()
    await other.goto(`/join/${code}`)
    await other.getByRole('button', { name: 'Join poll', exact: true }).click()
    await other.getByRole('button', { name: /B Red/ }).click()
    await other.getByRole('button', { name: 'Submit answer' }).click()
    await expect(page.getByRole('region', { name: 'Live results' })).toContainText('2 responses')
    await page.getByRole('button', { name: 'Show participant results' }).click()
    await expect(guest.getByRole('region', { name: 'Live results' })).toContainText('2 responses')
    for (const view of ['Pie chart', 'Donut chart', 'Data table', 'Bar graph']) {
      await page.getByRole('combobox', { name: 'Results format' }).click()
      await page.getByRole('option', { name: view, exact: true }).click()
      await expect(page.getByRole('region', { name: 'Live results' })).toContainText('2 responses')
    }
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'CSV', exact: true }).click()
    expect((await download).suggestedFilename()).toBe('blue-poll-results.csv')
    await guest.getByRole('tab', { name: 'Your answers' }).click()
    await expect(guest.getByText('Quiz score: 1 / 1', { exact: true })).toBeVisible()
    await guest.reload()
    await expect(guest.getByText('You’re all done!', { exact: true })).toBeVisible()
    await page.getByRole('combobox', { name: 'Results question' }).click()
    await page.getByRole('option', { name: '2. Describe your day.', exact: true }).click()
    await expect(page.getByLabel('Word cloud', { exact: true })).toContainText('skies')
    await page.getByText('Moderate open-ended answers (1)', { exact: true }).click()
    await page.getByRole('button', { name: 'Hide answer: Blue skies and sunny skies', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Live results' })).toContainText('0 responses')
    await page.getByRole('button', { name: 'Restore answer: Blue skies and sunny skies', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Live results' })).toContainText('1 response')
    await page.getByRole('button', { name: 'Hide participant results' }).click()
    await guest.getByRole('tab', { name: 'Live results' }).click()
    await expect(guest.getByText('Results are hidden', { exact: true })).toBeVisible()
    await other.getByRole('button', { name: 'Next question' }).click()
    await page.getByRole('button', { name: 'Close voting' }).click()
    await expect(other.getByText('Voting is closed. The host can reopen it if needed.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Present', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Exit presentation' })).toBeVisible()
    await page.getByRole('button', { name: 'Hide host view' }).click()
    await expect(page.getByText('Host results hidden', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Show host view' }).click()
    await expect(page.getByLabel('Word cloud', { exact: true })).toContainText('skies')
    await page.locator('.fixed.inset-0').evaluate(el => { el.scrollTop = 0 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'artifacts/poll-host-mobile.png', fullPage: true })
    await page.getByRole('button', { name: 'Exit presentation' }).click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.screenshot({ path: 'artifacts/poll-host-desktop.png', fullPage: true })
    expect(errors).toEqual([])
  } finally { await guestContext.close().catch(() => {}); await otherContext.close().catch(() => {}) }
})
