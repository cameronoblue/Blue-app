import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('mobile login, dashboard, logging, persisted notes, data, and settings', async ({ page }) => {
  const username = process.env.BLUE_E2E_USERNAME
  const password = process.env.BLUE_E2E_PASSWORD
  test.skip(!username || !password, 'Set BLUE_E2E_USERNAME and BLUE_E2E_PASSWORD to test the live dev deployment.')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await mkdir('artifacts', { recursive: true })
  await page.addInitScript(() => {
    const state = window as unknown as { locationCalls: number, locationDenied: boolean }
    state.locationCalls = 0
    state.locationDenied = false
    Object.defineProperty(navigator, 'geolocation', { value: { getCurrentPosition(success: PositionCallback, failure: PositionErrorCallback) {
      state.locationCalls++
      if (state.locationDenied) failure({ code: 1, message: 'Test denial', PERMISSION_DENIED: 1, POSITION_UNAVAILABLE: 2, TIMEOUT: 3 })
      else success({ coords: { latitude: 40, longitude: -80, accuracy: 15 }, timestamp: Date.now() } as GeolocationPosition)
    } } })
  })
  await page.goto('/sign-in')
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/blue-login-mobile.png', fullPage: true })
  await page.getByLabel('Username', { exact: true }).fill(username!)
  await page.getByLabel('Password', { exact: true }).fill(password!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^Hey,/ })).toBeVisible({ timeout: 20000 })
  await page.screenshot({ path: 'artifacts/blue-dashboard-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Open Log app' }).click()
  await expect(page.getByRole('heading', { name: 'Log app.' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Data', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Log location', exact: true })).toHaveCount(0)
  const eventName = `UI check ${Date.now()}`
  await page.getByRole('button', { name: 'New event', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Log location', exact: true })).not.toBeChecked()
  await page.getByLabel('Event name', { exact: true }).fill(eventName)
  await page.getByLabel(/Description/).fill('Temporary browser verification event')
  await page.getByRole('button', { name: 'Iris', exact: true }).click()
  await page.getByRole('button', { name: 'Create event', exact: true }).click()
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: eventName, exact: true }) })
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: 'Log it', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Moment captured' })).toBeVisible()
  await page.getByLabel(/Anything to add/).fill('A moment captured from the mobile app.')
  await page.getByRole('button', { name: 'Save note', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0, { timeout: 10000 })
  await page.screenshot({ path: 'artifacts/blue-log-mobile.png', fullPage: true })
  expect(await page.evaluate(() => (window as unknown as { locationCalls: number }).locationCalls)).toBe(0)
  await page.getByRole('button', { name: `Manage ${eventName}`, exact: true }).click()
  await page.getByRole('menuitem', { name: 'Edit event', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Log location', exact: true })).not.toBeChecked()
  await page.getByRole('checkbox', { name: 'Log location', exact: true }).check()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.reload()
  await expect(card.getByText('Location enabled', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: 'Log it', exact: true }).click()
  await page.getByRole('button', { name: 'Skip note', exact: true }).click()
  await expect(page.getByText('Location saved with your event', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as unknown as { locationCalls: number }).locationCalls)).toBe(1)
  await page.evaluate(() => { (window as unknown as { locationDenied: boolean }).locationDenied = true })
  await card.getByRole('button', { name: 'Log it', exact: true }).click()
  await page.getByRole('button', { name: 'Skip note', exact: true }).click()
  await expect(page.getByText('Location permission was denied. Your event was saved without location.', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Log app navigation' }).getByRole('link', { name: 'Data', exact: true }).click()
  await expect(page).toHaveURL(/\/log\/data$/)
  await expect(page.getByText('40.00000, -80.00000 · ±15 m', { exact: true })).toBeVisible()
  await expect(page.getByText('A moment captured from the mobile app.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('A moment captured from the mobile app.', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: `Edit note for ${eventName}`, exact: true }).last().click()
  await page.getByLabel(/Your note/).fill('Updated note, persisted in Convex.')
  await page.getByRole('button', { name: 'Save note', exact: true }).click()
  await expect(page.getByText('Updated note, persisted in Convex.', { exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export recent', exact: true }).click()
  expect((await downloadPromise).suggestedFilename()).toMatch(/^blue-log-.*\.csv$/)
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0, { timeout: 10000 })
  await page.screenshot({ path: 'artifacts/blue-data-mobile.png', fullPage: true })
  for (let remaining = 3; remaining > 0; remaining--) {
    await page.getByRole('button', { name: `Delete entry for ${eventName}`, exact: true }).first().click()
    await page.getByRole('button', { name: 'Delete moment', exact: true }).click()
    await expect(page.getByRole('button', { name: `Delete entry for ${eventName}`, exact: true })).toHaveCount(remaining - 1)
  }
  await expect(page.getByText('Updated note, persisted in Convex.', { exact: true })).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Log app navigation' }).getByRole('link', { name: 'Events', exact: true }).click()
  await page.getByRole('button', { name: `Manage ${eventName}`, exact: true }).click()
  await page.getByRole('menuitem', { name: 'Delete empty event', exact: true }).click()
  await page.getByRole('button', { name: 'Delete event', exact: true }).click()
  await expect(page.getByRole('heading', { name: eventName, exact: true })).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'People', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add person', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0, { timeout: 10000 })
  await page.screenshot({ path: 'artifacts/blue-settings-dark-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Light', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: /^Hey,/ })).toBeVisible()
  await page.screenshot({ path: 'artifacts/blue-dashboard-desktop.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
