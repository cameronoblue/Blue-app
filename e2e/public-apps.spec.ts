import { test, expect } from '@playwright/test'

test('visitors can discover basketball, finish a guest run, and replay without signing in', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Public navigation' }).getByRole('link', { name: 'Public apps', exact: true }).click()
  await expect(page).toHaveURL(/\/public-apps$/)
  await expect(page.getByText('NO LOGIN NEEDED', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Play basketball', exact: true }).click()
  await expect(page).toHaveURL(/\/basketball$/)
  await page.clock.runFor(32)
  await expect(page.getByRole('heading', { name: 'Find your flick.' })).toBeVisible()
  await page.getByRole('button', { name: 'Let’s play', exact: true }).click()
  const canvas = page.locator('canvas')
  await canvas.scrollIntoViewIfNeeded()
  const box = (await canvas.boundingBox())!
  const x = box.x + box.width / 2, y = box.y + box.height * 475 / 540
  const session = await context.newCDPSession(page)
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + box.width * 12 / 390, y: y - box.height * 120 / 540 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.clock.runFor(2500)
  await expect(page.getByTestId('basketball-score')).toHaveText('2')
  await page.clock.fastForward(61000)
  await page.clock.runFor(32)
  await expect(page.getByRole('heading', { name: '2 points', exact: true })).toBeVisible()
  await expect(page.getByText('Guest run complete. Play again anytime.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Play again', exact: true }).click()
  await expect(page.getByTestId('basketball-score')).toHaveText('0')
  await expect(page.getByTestId('basketball-timer')).toHaveText('60s')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.clock.resume()
  await page.screenshot({ path: 'artifacts/public-basketball-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/apps')
  await expect(page).toHaveURL(/\/sign-in$/)
  expect(errors).toEqual([])
})

test('guests can shoot again before the previous ball returns', async ({ page }) => {
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await page.goto('/basketball')
  await page.clock.runFor(32)
  await page.getByRole('button', { name: 'Let’s play', exact: true }).click()
  const canvas = page.locator('canvas')
  await canvas.press('Space')
  await page.clock.runFor(150)
  await canvas.press('Space')
  await expect(page.getByTestId('basketball-attempts')).toHaveText('0 baskets from 2 shots')
  await page.clock.runFor(150)
  await canvas.press('Space')
  await expect(page.getByTestId('basketball-attempts')).toHaveText('0 baskets from 3 shots')
  await page.clock.runFor(4000)
  await expect(page.getByTestId('basketball-attempts')).toContainText('3 shots')
})
