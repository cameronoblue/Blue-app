import { test, expect, type Page } from '@playwright/test'
test.use({ actionTimeout: 10000 })
async function login(page: Page) {
  const username = process.env.BLUE_E2E_USERNAME, password = process.env.BLUE_E2E_PASSWORD
  test.skip(!username || !password, 'Development admin credentials required.')
  await page.goto('/sign-in')
  await page.getByLabel('Username', { exact: true }).fill(username!)
  await page.getByLabel('Password', { exact: true }).fill(password!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/apps$/)
}
test('sidebar collapses and Apps expands on hover, keyboard, and mobile tap', async ({ page }) => {
  await login(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(nav.getByRole('link', { name: 'Log app', exact: true })).toHaveCount(0)
  await nav.getByRole('button', { name: 'Apps', exact: true }).hover()
  await expect(nav.getByRole('link', { name: 'Log app', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Games', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Polls & quizzes', exact: true })).toBeVisible()
  await page.getByRole('heading', { name: /Hey,/ }).hover()
  await expect(nav.getByRole('link', { name: 'Log app', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Close sidebar', exact: true }).click()
  await expect.poll(() => page.getByRole('complementary', { name: 'Workspace sidebar' }).evaluate(el => el.getBoundingClientRect().width)).toBeLessThan(100)
  await nav.getByRole('button', { name: 'Apps', exact: true }).focus()
  await nav.getByRole('button', { name: 'Apps', exact: true }).press('Enter')
  await expect(nav.getByRole('link', { name: 'Polls & quizzes', exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Polls & quizzes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Polls & quizzes.', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Open sidebar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Close sidebar', exact: true })).toBeVisible()
  await expect.poll(() => page.getByRole('complementary', { name: 'Workspace sidebar' }).evaluate(el => el.getBoundingClientRect().width)).toBeGreaterThan(230)
  await page.screenshot({ path: 'artifacts/sidebar-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation', exact: true }).tap()
  const drawer = page.getByRole('dialog', { name: 'Blue workspace', exact: true })
  await expect(drawer).toBeVisible()
  await drawer.getByRole('button', { name: 'Apps', exact: true }).tap()
  await drawer.getByRole('link', { name: 'Log app', exact: true }).tap()
  await expect(page.getByRole('heading', { name: 'Log app.', exact: true })).toBeVisible()
  await expect(drawer).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('host leads multiple-answer rounds on a separate audience screen', async ({ page, browser }) => {
  test.setTimeout(120000)
  await login(page)
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.locator('.app-card').filter({ hasText: 'Polls & quizzes' }).click()
  await page.getByRole('link', { name: 'Create poll', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Host controls each question', exact: true })).toBeChecked()
  await page.getByLabel('Poll title', { exact: true }).fill(`Host-led test ${Date.now()}`)
  const first = page.getByRole('region', { name: 'Question 1', exact: true })
  await first.getByLabel('Question text', { exact: true }).fill('Which colors are blue?')
  await first.getByLabel('Option 1', { exact: true }).fill('Navy')
  await first.getByLabel('Option 2', { exact: true }).fill('Sky')
  await first.getByRole('button', { name: 'Add option', exact: true }).click()
  await first.getByLabel('Option 3', { exact: true }).fill('Red')
  await first.getByRole('checkbox', { name: 'Accept multiple answers', exact: true }).check()
  await first.getByRole('checkbox', { name: 'Correct option 1 · Navy', exact: true }).check()
  await first.getByRole('checkbox', { name: 'Correct option 2 · Sky', exact: true }).check()
  await page.getByRole('button', { name: /Add question/ }).click()
  const second = page.getByRole('region', { name: 'Question 2', exact: true })
  await second.getByLabel('Question text', { exact: true }).fill('Describe the sky.')
  await page.getByRole('combobox', { name: 'Question 2 type' }).click()
  await page.getByRole('option', { name: 'Open ended', exact: true }).click()
  await page.getByRole('button', { name: 'Create draft', exact: true }).click()
  const code = (await page.getByTestId('poll-code').textContent())!
  await page.getByRole('button', { name: 'Publish lobby', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Start first question', exact: true })).toBeVisible()
  // This audience window shares the host's auth; it must still obey public reveal rules.
  const popup = page.waitForEvent('popup')
  await page.getByRole('link', { name: 'Open audience screen', exact: true }).click()
  const audience = await popup
  await audience.setViewportSize({ width: 1280, height: 800 })
  audience.on('pageerror', e => errors.push(e.message))
  await expect(audience.getByTestId('audience-code')).toHaveText(code)
  await expect(audience.getByText('Which colors are blue?', { exact: true })).toHaveCount(0)
  await expect(audience.getByRole('button', { name: 'Reveal results' })).toHaveCount(0)
  const guestContext = await browser.newContext({ baseURL: 'http://localhost:5173', viewport: { width: 390, height: 844 } })
  const guest = await guestContext.newPage()
  try {
    await guest.goto(`/join/${code}`)
    await guest.getByRole('button', { name: 'Join poll', exact: true }).click()
    await expect(guest.getByRole('heading', { name: 'You’re in!', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Start first question', exact: true }).click()
    await expect(guest.getByRole('heading', { name: 'Which colors are blue?', exact: true })).toBeVisible()
    await expect(audience.getByRole('heading', { name: 'Which colors are blue?', exact: true })).toBeVisible()
    await expect(guest.getByText('Describe the sky.', { exact: true })).toHaveCount(0)
    await guest.getByRole('checkbox', { name: 'Navy', exact: true }).check()
    await guest.getByRole('checkbox', { name: 'Sky', exact: true }).check()
    await guest.getByRole('button', { name: 'Submit answer', exact: true }).click()
    await expect(guest.getByRole('heading', { name: 'Answer submitted', exact: true })).toBeVisible()
    await expect(audience.getByText('1 / 1 answered', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Lock answers', exact: true }).click()
    await expect(audience.getByText('Answers are locked. Results coming up.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Reopen answers', exact: true }).click()
    await page.getByRole('button', { name: 'Reveal results', exact: true }).click()
    await expect(audience.getByRole('img', { name: /^Bar graph:/ })).toBeVisible()
    await page.getByRole('combobox', { name: 'Results format', exact: true }).click()
    await page.getByRole('option', { name: 'Pie chart', exact: true }).click()
    await expect(audience.getByRole('img', { name: /^pie chart:/ })).toBeVisible()
    await page.getByRole('button', { name: 'Hide audience results', exact: true }).click()
    await expect(audience.getByText('Results are hidden', { exact: true })).toBeVisible()
    await expect(guest.getByText('Results are hidden', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Show audience results', exact: true }).click()
    await page.getByRole('button', { name: 'Next question', exact: true }).click()
    await expect(guest.getByRole('heading', { name: 'Describe the sky.', exact: true })).toBeVisible()
    await expect(audience.getByRole('heading', { name: 'Describe the sky.', exact: true })).toBeVisible()
    await guest.getByLabel('Your answer', { exact: true }).fill('Bright blue skies')
    await guest.getByRole('button', { name: 'Submit answer', exact: true }).click()
    await expect(guest.getByRole('heading', { name: 'Answer submitted', exact: true })).toBeVisible()
    await guest.reload()
    await expect(guest.getByRole('heading', { name: 'Answer submitted', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Reveal results', exact: true }).click()
    await expect(audience.getByLabel('Word cloud', { exact: true })).toContainText('skies')
    await audience.screenshot({ path: 'artifacts/poll-audience-desktop.png', fullPage: true })
    await page.screenshot({ path: 'artifacts/live-host-mobile.png', fullPage: true })
    await guest.screenshot({ path: 'artifacts/live-guest-mobile.png', fullPage: true })
    expect(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Finish session', exact: true }).click()
    await expect(audience.getByRole('heading', { name: 'Thanks for playing.', exact: true })).toBeVisible()
    await expect(guest.getByText('Quiz score: 1 / 1', { exact: true })).toBeVisible()
    expect(errors).toEqual([])
  } finally { await guestContext.close().catch(() => {}); await audience.close().catch(() => {}) }
})
