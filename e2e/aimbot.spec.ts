import { test, expect } from '@playwright/test'

test('admin aimbot makes shots and keeps the completed round out of saved scores', async ({ page }) => {
  const username = process.env.BLUE_E2E_USERNAME, password = process.env.BLUE_E2E_PASSWORD
  test.skip(!username || !password, 'Development admin credentials required.')
  await page.goto('/basketball')
  await expect(page.getByRole('checkbox', { name: 'Aimbot', exact: true })).toHaveCount(0)
  await page.goto('/sign-in')
  await page.getByLabel('Username', { exact: true }).fill(username!)
  await page.getByLabel('Password', { exact: true }).fill(password!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/apps$/)
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await page.locator('.app-card').filter({ hasText: 'Games' }).click()
  await page.getByRole('link', { name: /Play basketball/ }).click()
  const checkbox = page.getByRole('checkbox', { name: 'Aimbot', exact: true })
  await checkbox.check()
  await expect(page.getByText('Practice mode - High scores disabled', { exact: true })).toBeVisible()
  await page.clock.runFor(32)
  const best = await page.locator('.basketball-controls strong').textContent()
  await page.getByRole('button', { name: 'Let’s play', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Find your flick.' })).toHaveCount(0)
  await expect(checkbox).toBeDisabled()
  await page.clock.runFor(32)
  const canvas = page.locator('canvas')
  await canvas.press('ArrowLeft')
  await canvas.press('Space')
  await page.clock.runFor(300)
  await canvas.press('ArrowRight')
  await canvas.press('Space')
  await page.clock.runFor(2500)
  await expect(page.getByTestId('basketball-attempts')).toHaveText('2 baskets from 2 shots')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(checkbox).toBeDisabled()
  await page.getByRole('button', { name: 'Finish this run', exact: true }).click()
  await page.clock.runFor(100)
  await expect(page.getByText('Aimbot practice - excluded from high scores.', { exact: true })).toBeVisible()
  await expect(page.locator('.basketball-controls strong')).toHaveText(best!)
  await checkbox.uncheck()
  await page.getByRole('button', { name: 'Play again', exact: true }).click()
  await expect(page.getByTestId('basketball-score')).toHaveText('0')
})


